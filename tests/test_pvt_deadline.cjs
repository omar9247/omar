'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const source = fs.readFileSync('web/static/app.js', 'utf8');
const part = source.slice(source.indexOf('// ---------- check-in (FR-12)'), source.indexOf('// ---------- crew (FR-17)'));
let now = 1000, stimulus, cleared = 0;
const elements = {};
const ctx = { $: (id) => elements[id] ||= {}, Date: { now: () => now }, PVT_MS: 90000, LAPSE_MS: 355,
  clearTimeout: () => { cleared++; }, setTimeout: (fn) => { stimulus = fn; return 1; } };
vm.runInNewContext(part + '\nglobalThis.test = {pvt, pvtPress, pvtStats};', ctx);
const { pvt, pvtPress, pvtStats } = ctx.test;
pvtPress();
assert.equal(pvt.end, 91000);
now = pvt.end;
pvtStats();
assert.equal(pvt.running, false, 'the 90-second test must end even when no stimulus is answered');
assert.equal(elements['pvt-big'].textContent, 'Done');
assert(cleared > 0);
stimulus();
assert.equal(pvt.go, false, 'a queued stimulus must not turn on after completion');
now += 100;
pvtPress();
pvt.go = true; pvt.t0 = now;
now = pvt.end + 1;
pvtPress();
assert.equal(pvt.running, false);
assert.equal(pvt.trials.length, 0, 'a response after the deadline is not a valid trial');
console.log('PVT deadline checks passed; 90 seconds, 355 ms lapse cutoff and original stimulus timing preserved.');
